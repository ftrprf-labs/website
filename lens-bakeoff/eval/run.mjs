// Bake-off runner. Runs each lens over each case under TWO gate profiles:
//   frozen   = only the four website families count as "undeniable" (the current engine)
//   extended = quantitative families (CONCENTRATION, TREND_DIVERGENCE) also count as undeniable
// The delta between them is the empirical measure of the "just configuration on the engine" hypothesis.
//
// Output: out/results.json (full) and out/reveal-gallery.md (curated), plus a console summary.

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { runEngine, DEFAULT_GATE_CONFIG, FROZEN_UNDENIABLE, EXTENDED_UNDENIABLE } from '../engine/engine.mjs';
import { reputationLens } from '../lenses/reputation.mjs';
import { financeLens } from '../lenses/finance.mjs';
import { dependencyLens } from '../lenses/dependency.mjs';
import { CASES } from '../cases/cases.mjs';
import { scoreReveal, summarise } from './evaluators.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'out');
mkdirSync(OUT, { recursive: true });

const LENSES = [reputationLens, financeLens, dependencyLens];
const FROZEN = { ...DEFAULT_GATE_CONFIG, undeniable: FROZEN_UNDENIABLE };
const EXTENDED = { ...DEFAULT_GATE_CONFIG, undeniable: EXTENDED_UNDENIABLE };

const results = { generatedFor: 'lens-2-bakeoff', lenses: {}, gateGap: {} };
const perLensFrozen = {};

for (const lens of LENSES) {
  const rowsFrozen = [];
  const rowsExtended = [];
  let gapCount = 0;
  const gapCases = [];
  for (const c of CASES) {
    const rf = runEngine(lens, c, FROZEN);
    const re = runEngine(lens, c, EXTENDED);
    const scoresF = rf.outcome === 'REVEAL' ? scoreReveal(lens.id, rf.reveal) : null;
    rowsFrozen.push({
      caseId: c.id, label: c.label, outcome: rf.outcome,
      reveal: rf.reveal ? { family: rf.reveal.family, cross_lens: rf.reveal.cross_lens, wording: rf.reveal.wording, why: rf.reveal.why_might_matter, significance: rf.reveal.significance, basis: rf.reveal.basis } : null,
      scores: scoresF,
      suppressions: rf.suppressions || [],
      reason: rf.reason,
    });
    rowsExtended.push({ caseId: c.id, outcome: re.outcome, family: re.reveal ? re.reveal.family : null });
    if (rf.outcome !== 'REVEAL' && re.outcome === 'REVEAL') { gapCount += 1; gapCases.push({ caseId: c.id, family: re.reveal.family, wording: re.reveal.wording }); }
  }
  // Candidate-level suppression across ALL cases (even those that still revealed via another
  // relation). This is the precise "just configuration" evidence: how many candidates the frozen
  // gate refuses, by family and by check.
  const suppByFamily = {};
  const suppByCheck = {};
  for (const c of CASES) {
    const rf = runEngine(lens, c, FROZEN);
    for (const g of rf.gatedAll || []) {
      if (g.passed) continue;
      suppByFamily[g.family] = (suppByFamily[g.family] || 0) + 1;
      const check = (g.reason || '').split(':')[0];
      suppByCheck[check] = (suppByCheck[check] || 0) + 1;
    }
  }
  results.lenses[lens.id] = { name: lens.name, frozen: rowsFrozen, extended: rowsExtended, summary: summarise(lens.id, rowsFrozen) };
  results.gateGap[lens.id] = {
    suppressedByFrozenButRevealedByExtended: gapCount, cases: gapCases,
    candidateSuppressionsByFamily: suppByFamily, candidateSuppressionsByCheck: suppByCheck,
  };
  perLensFrozen[lens.id] = rowsFrozen;
}

writeFileSync(join(OUT, 'results.json'), JSON.stringify(results, null, 2));

// ---- Reveal Gallery ---------------------------------------------------------
const provenanceNote = 'All cases are SYNTHETIC fixtures (crafted), clearly labelled. No real personal or sensitive financial data is used. Example reveal copy is prototype output of the harness, grounded in the synthetic evidence.';
let g = `# Reveal Gallery (Lens 2 Bake-off)\n\n> Generated by \`lens-bakeoff/eval/run.mjs\` against 14 synthetic cases. ${provenanceNote}\n>\n> Evidence label for every reveal below: PROTOTYPE OUTPUT on SYNTHETIC evidence. Scores are heuristic\n> proxies (see \`eval/evaluators.mjs\`); the axis that truly settles the bake-off is human confirmed-new\n> recognition, which a synthetic harness cannot produce. Gate column shows whether the FROZEN engine\n> (four website families) surfaces it; some finance and dependency reveals only surface under an\n> EXTENDED gate, which is itself the central finding.\n\n`;

for (const lens of LENSES) {
  const rows = perLensFrozen[lens.id];
  const s = results.lenses[lens.id].summary;
  g += `\n## ${lens.name}\n\n`;
  g += `Reveal rate ${Math.round(s.revealRate * 100)}%, silence rate ${Math.round(s.silenceRate * 100)}%, insufficient ${s.insufficient}, trivial reveals ${s.trivialReveals}. `;
  g += `Mean WOW ${s.meanWow}, mean surprise ${s.meanSurprise}, mean non-triviality ${s.meanNonTriviality}, mean evidence strength ${s.meanEvidenceStrength}, mean false-positive risk ${s.meanFalsePositiveRisk}.\n\n`;
  const reveals = rows.filter((r) => r.outcome === 'REVEAL').sort((a, b) => (b.scores.wow - a.scores.wow) || (b.scores.surprise - a.scores.surprise));
  g += `### Reveals (best first by WOW)\n\n`;
  if (!reveals.length) g += `_No reveals surfaced under the frozen gate._\n\n`;
  for (const r of reveals) {
    g += `- **${r.label}** [PROTOTYPE / SYNTHETIC] family ${r.reveal.family}${r.reveal.cross_lens ? ' (cross-lens)' : ''}, WOW ${r.scores.wow}/5, surprise ${r.scores.surprise}/5, non-triviality ${r.scores.nonTriviality}/5, FP-risk ${r.scores.falsePositiveRisk}/5.\n`;
    g += `  - Reveal: "${r.reveal.wording}"\n`;
    g += `  - Waarom het ertoe doet: ${r.reveal.why}\n`;
    const b = (r.reveal.basis || []).map((x) => `${x.surface}:${x.value}`).slice(0, 3).join(' | ');
    if (b) g += `  - Bewijs (waar zie je dat): ${b}\n`;
  }
  // Notable silences.
  const silences = rows.filter((r) => r.outcome === 'SILENCE');
  if (silences.length) {
    g += `\n### Silences (a designed success)\n\n`;
    for (const r of silences) {
      const why = (r.suppressions && r.suppressions.length) ? r.suppressions.map((x) => `${x.family}: ${x.reason}`).join('; ') : r.reason;
      g += `- ${r.label}: ${why}\n`;
    }
  }
  const insuff = rows.filter((r) => r.outcome === 'INSUFFICIENT');
  if (insuff.length) {
    g += `\n### Insufficient evidence (honest "I could not look")\n\n`;
    for (const r of insuff) g += `- ${r.label}: ${r.reason}\n`;
  }
}

// Gate-gap section (the hypothesis finding).
g += `\n## Gate gap: frozen vs extended (the "just configuration" test)\n\n`;
g += `For each lens, cases the FROZEN gate suppresses but an EXTENDED gate (admitting CONCENTRATION and\nTREND_DIVERGENCE as undeniable) would surface. A non-zero count means the lens needs more than\nconfiguration on the current engine: it needs a new relation family and a gate that understands it.\n\n`;
for (const lens of LENSES) {
  const gg = results.gateGap[lens.id];
  g += `- **${lens.name}**: ${gg.suppressedByFrozenButRevealedByExtended} case(s) suppressed by the frozen gate.`;
  if (gg.cases.length) g += ` Families: ${[...new Set(gg.cases.map((x) => x.family))].join(', ')}.`;
  g += `\n`;
}

writeFileSync(join(OUT, 'reveal-gallery.md'), g);

// ---- Console summary --------------------------------------------------------
console.log('\n=== Lens 2 Bake-off summary (frozen gate) ===');
for (const lens of LENSES) {
  const s = results.lenses[lens.id].summary;
  console.log(`\n${lens.name} (${lens.id})`);
  console.log(`  reveals ${s.reveals}/${s.cases}  silence ${Math.round(s.silenceRate * 100)}%  insufficient ${s.insufficient}  failures ${s.failures}  trivial ${s.trivialReveals}`);
  console.log(`  meanWOW ${s.meanWow}  surprise ${s.meanSurprise}  nonTriv ${s.meanNonTriviality}  evStrength ${s.meanEvidenceStrength}  FPrisk ${s.meanFalsePositiveRisk}  action ${s.meanActionRelevance}`);
  console.log(`  run: TTFV ${s.run.timeToFirstValue} userData ${s.run.userDataRequired} integ ${s.run.integrationDependency} cost ${s.run.costPerRun} repeat ${s.run.repeatability}`);
  console.log(`  gate gap (suppressed by frozen, revealed by extended): ${results.gateGap[lens.id].suppressedByFrozenButRevealedByExtended}`);
}
console.log('\nWrote out/results.json and out/reveal-gallery.md');
